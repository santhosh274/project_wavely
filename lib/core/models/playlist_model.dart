/// Where a playlist came from.
///
/// Genre playlists are derived from the device on every scan and are thrown away
/// and rebuilt each time. User playlists are created by the user and must survive
/// a rescan, so they are kept separately and never overwritten by a reload.
enum PlaylistSource { genre, user }

/// Wavely Playlist Model
class WavelyPlaylist {
  final String id;
  final String name;
  final List<String> songIds;
  final DateTime createdAt;

  /// Whether this playlist was generated from genres or made by the user.
  final PlaylistSource source;

  const WavelyPlaylist({
    required this.id,
    required this.name,
    required this.songIds,
    required this.createdAt,
    this.source = PlaylistSource.user,
  });

  int get songCount => songIds.length;

  /// Whether the playlist is built from genres and rebuilt on every scan.
  bool get isAutoGenerated => source == PlaylistSource.genre;

  WavelyPlaylist copyWith({
    String? id,
    String? name,
    List<String>? songIds,
    DateTime? createdAt,
    PlaylistSource? source,
  }) {
    return WavelyPlaylist(
      id: id ?? this.id,
      name: name ?? this.name,
      songIds: songIds ?? this.songIds,
      createdAt: createdAt ?? this.createdAt,
      source: source ?? this.source,
    );
  }
}
