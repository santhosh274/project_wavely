import 'package:flutter/material.dart';
import 'package:flutter_test/flutter_test.dart';
import 'package:wavely/features/library/controllers/library_controller.dart';

import 'support/fake_media_service.dart';

void main() {
  late FakeLocalMediaService media;
  late LibraryController library;

  setUp(() {
    media = FakeLocalMediaService(libraryFixture());
    library = LibraryController(mediaService: media);
  });

  tearDown(() => library.dispose());

  /// The controller defers its first scan until after the first frame, because a
  /// permission dialog needs a foreground Activity to attach to.
  Future<void> pumpFirstLoad(WidgetTester tester) async {
    await tester.pumpWidget(const SizedBox.shrink());
    await tester.pump();
    await tester.pump(const Duration(milliseconds: 100));
  }

  group('library scan', () {
    testWidgets('groups tracks into albums, artists and genre playlists',
        (tester) async {
      await pumpFirstLoad(tester);

      expect(library.allSongs, hasLength(4));
      expect(library.albums.map((a) => a.albumName), ['Harbour Lights', 'Slow Light']);
      expect(library.artists.map((a) => a.artistName), ['Vela', 'Kite']);
      expect(library.playlists.map((p) => p.name), containsAll(['Ambient', 'Folk']));
      expect(library.genres, ['Ambient', 'Folk']);
    });

    testWidgets('genre playlists are marked as generated, not the user\'s',
        (tester) async {
      await pumpFirstLoad(tester);

      expect(library.playlists.every((p) => p.isAutoGenerated), isTrue);
      expect(library.userPlaylists, isEmpty);
    });

    testWidgets('a declined permission is reported, not filled in with tracks',
        (tester) async {
      media.permissionGranted = false;
      final denied = LibraryController(mediaService: media);
      addTearDown(denied.dispose);

      await tester.pumpWidget(const SizedBox.shrink());
      await tester.pump();
      await tester.pump(const Duration(milliseconds: 100));

      // The point is that this is distinguishable from a device with no music.
      expect(denied.allSongs, isEmpty);
      expect(denied.needsPermission, isTrue);
      expect(denied.statusMessage, isNotNull);
    });
  });

  group('search and filtering', () {
    testWidgets('a query matches title, artist, album and genre',
        (tester) async {
      await pumpFirstLoad(tester);

      library.setSearchQuery('neon');
      expect(library.songs.map((s) => s.title), ['Neon Tide']);

      library.setSearchQuery('kite');
      expect(library.songs, hasLength(2));

      library.setSearchQuery('slow light');
      expect(library.songs, hasLength(2));
    });

    testWidgets('a genre chip filters on genre, not on matching text',
        (tester) async {
      await pumpFirstLoad(tester);

      library.setGenreFilter('Folk');

      expect(library.songs.map((s) => s.id), ['3', '4']);
      expect(library.selectedGenre, 'Folk');
      expect(library.searchQuery, isEmpty);
    });

    testWidgets('typing takes over from a genre chip', (tester) async {
      await pumpFirstLoad(tester);

      library.setGenreFilter('Folk');
      library.setSearchQuery('dust');

      // Otherwise the results stay narrowed by a chip the user cannot see.
      expect(library.selectedGenre, isNull);
      expect(library.songs.map((s) => s.title), ['Dust and Gold']);
    });

    testWidgets('clearing resets the query and the genre together',
        (tester) async {
      await pumpFirstLoad(tester);

      library.setSearchQuery('neon');
      library.clearSearchQuery();

      expect(library.hasActiveFilter, isFalse);
      expect(library.songs, hasLength(4));
    });

    testWidgets('all songs ignores an active search', (tester) async {
      await pumpFirstLoad(tester);

      library.setSearchQuery('neon');

      // "All Songs" has to keep meaning all of them.
      expect(library.songs, hasLength(1));
      expect(library.allSongs, hasLength(4));
    });
  });

  group('collections', () {
    testWidgets('albums and artists resolve back to their tracks',
        (tester) async {
      await pumpFirstLoad(tester);

      expect(
        library.songsInAlbum('Harbour Lights').map((s) => s.id),
        ['1', '2'],
      );
      expect(library.songsByArtist('Kite').map((s) => s.id), ['3', '4']);
      expect(library.songsInAlbum('No Such Album'), isEmpty);
      expect(library.songsByArtist('No Such Artist'), isEmpty);
    });

    testWidgets('recently added is the newest end of the library',
        (tester) async {
      await pumpFirstLoad(tester);

      expect(
        library.recentlyAdded(limit: 2).map((s) => s.id),
        ['1', '2'],
      );
    });

    testWidgets('total runtime adds up the given tracks', (tester) async {
      await pumpFirstLoad(tester);

      // 3 + 4 + 2 + 5 minutes.
      expect(
        library.totalDurationOf(library.allSongs),
        const Duration(minutes: 14),
      );
    });

    testWidgets('favourites follow the toggle, not a separate list',
        (tester) async {
      await pumpFirstLoad(tester);
      expect(library.favorites, isEmpty);

      library.toggleFavorite('2');

      expect(library.favorites.map((s) => s.id), ['2']);
      expect(library.allSongs.firstWhere((s) => s.id == '2').isFavorite, isTrue);
    });
  });

  group('play history', () {
    testWidgets('starts empty rather than showing unplayed tracks',
        (tester) async {
      await pumpFirstLoad(tester);

      // Backfilling this with library songs would claim songs had been heard.
      expect(library.recentlyPlayed, isEmpty);
    });

    testWidgets('records tracks newest first and resolves them to songs',
        (tester) async {
      await pumpFirstLoad(tester);

      library.recordPlayed('2');
      library.recordPlayed('4');

      expect(library.recentlyPlayed.map((s) => s.id), ['4', '2']);
    });

    testWidgets('replaying a track moves it to the top without duplicating',
        (tester) async {
      await pumpFirstLoad(tester);

      library.recordPlayed('2');
      library.recordPlayed('4');
      library.recordPlayed('2');

      expect(library.recentlyPlayed.map((s) => s.id), ['2', '4']);
    });

    testWidgets('drops history entries for tracks that are gone', (tester) async {
      await pumpFirstLoad(tester);

      library.recordPlayed('2');
      library.recordPlayed('999');

      // The missing id must not break the list of real ones.
      expect(library.recentlyPlayed.map((s) => s.id), ['2']);
    });
  });

  group('playlists', () {
    testWidgets('a created playlist is listed among the playlists',
        (tester) async {
      await pumpFirstLoad(tester);

      library.createPlaylist('Road Trip');

      expect(library.playlists.map((p) => p.name), contains('Road Trip'));
      expect(library.userPlaylists.map((p) => p.name), ['Road Trip']);
    });

    testWidgets('user playlists survive a rescan of the device', (tester) async {
      await pumpFirstLoad(tester);
      library.createPlaylistWithSong('Road Trip', '1');

      // The genre playlists are rebuilt here, which is exactly what used to
      // delete everything the user had made.
      await library.loadLibrary();

      expect(library.userPlaylists.map((p) => p.name), ['Road Trip']);
      expect(library.songsInPlaylist(library.userPlaylists.single.id),
          hasLength(1));
    });

    testWidgets('tracks can be added to and removed from a playlist',
        (tester) async {
      await pumpFirstLoad(tester);
      final playlist = library.createPlaylist('Road Trip');

      expect(library.addToPlaylist(playlistId: playlist.id, songId: '1'), isTrue);
      expect(library.addToPlaylist(playlistId: playlist.id, songId: '2'), isTrue);
      expect(library.playlistContains(playlist.id, '2'), isTrue);
      // Adding the same track twice must not duplicate it.
      library.addToPlaylist(playlistId: playlist.id, songId: '2');
      expect(library.songsInPlaylist(playlist.id), hasLength(2));

      expect(
        library.removeFromPlaylist(playlistId: playlist.id, songId: '1'),
        isTrue,
      );
      expect(library.songsInPlaylist(playlist.id).map((s) => s.id), ['2']);
    });

    testWidgets('adding to an unknown playlist reports failure', (tester) async {
      await pumpFirstLoad(tester);

      expect(library.addToPlaylist(playlistId: 'nope', songId: '1'), isFalse);
      expect(
        library.removeFromPlaylist(playlistId: 'nope', songId: '1'),
        isFalse,
      );
      expect(library.songsInPlaylist('nope'), isEmpty);
    });

    testWidgets('a deleted playlist is gone for good', (tester) async {
      await pumpFirstLoad(tester);
      final playlist = library.createPlaylist('Road Trip');

      expect(library.deletePlaylist(playlist.id), isTrue);
      expect(library.userPlaylists, isEmpty);

      await library.loadLibrary();
      expect(library.playlists.map((p) => p.name), isNot(contains('Road Trip')));
    });

    testWidgets('playlist lookups skip tracks that are no longer on the device',
        (tester) async {
      await pumpFirstLoad(tester);
      final playlist = library.createPlaylistWithSong('Road Trip', '1');
      library.addToPlaylist(playlistId: playlist.id, songId: '2');

      // A track deleted from the device must not leave a blank row behind.
      media.songs = libraryFixture().where((s) => s.id != '1').toList();
      await library.loadLibrary();

      expect(library.songsInPlaylist(playlist.id).map((s) => s.id), ['2']);
    });
  });
}